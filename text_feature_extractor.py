"""Модуль извлечения текстовых признаков из обстоятельств судебных дел КоАП 12.8.

Содержит класс TextFeatureExtractor, который парсит русскоязычные тексты
судебных постановлений и извлекает булевы и категориальные признаки для ML-вектора.
"""

from __future__ import annotations

import logging
import re

__all__ = ["TextFeatureExtractor"]

logger = logging.getLogger(__name__)


class TextFeatureExtractor:
    """Извлекает структурированные признаки из текста обстоятельств судебного дела.

    Все regex-паттерны хранятся как константы класса. Методы принимают строку
    (текст поля ``circumstances`` либо полного текстового блока) и возвращают
    скалярное значение признака.

    Пример использования::

        extractor = TextFeatureExtractor()
        text = "водитель прошёл медицинское освидетельствование, промилле 0.8"
        exam = extractor.extract_medical_examination(text)   # 2
        level = extractor.extract_alcohol_level_known(text)  # True
    """

    # ------------------------------------------------------------------
    # Константы: паттерны медицинского освидетельствования
    # ------------------------------------------------------------------

    #: Водитель отказался от освидетельствования
    _RE_MED_REFUSED: re.Pattern[str] = re.compile(
        r"отказ(?:ался|алась|ано)?\s+от\s+(?:прохождения\s+)?(?:медицинского\s+)?освидетельствован",
        re.IGNORECASE,
    )

    #: Освидетельствование проводилось (любое упоминание прохождения)
    _RE_MED_CONDUCTED: re.Pattern[str] = re.compile(
        r"(?:"
        r"(?:прошёл|прошел|прошла|прошли|прошло)\s+(?:медицинское\s+)?освидетельствован"
        r"|освидетельствован(?:ие|ия|ию|ием)\s+(?:был|проведено|установило|показало)"
        r"|(?:медицинское\s+)?освидетельствован(?:ие|ия)\s+(?:в|на|при|по)"
        r"|акт\s+(?:медицинского\s+)?освидетельствован"
        r"|результат(?:ы|ами|ов)\s+(?:медицинского\s+)?освидетельствован"
        r"|направлен\s+на\s+(?:медицинское\s+)?освидетельствован"
        r"|(?:медицинского\s+)?освидетельствования\s+(?:показали|установили|выявили)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: паттерны уровня алкоголя
    # ------------------------------------------------------------------

    #: Числовое значение промилле / мг/л
    _RE_ALCOHOL_LEVEL: re.Pattern[str] = re.compile(
        r"(?:"
        r"\d+[,.]?\d*\s*(?:промилл[еи]|мг/л|мг\s*на\s*литр|‰)"
        r"|\d+[,.]?\d*\s*(?:г(?:рамм)?/л)"
        r"|концентрац\w+\s+алкоголя\s+(?:составил|равн|был)\w*\s+\d"
        r"|алкоголь\w*\s+\d+[,.]?\d*"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: признание вины
    # ------------------------------------------------------------------

    #: Водитель признал / не оспаривает вину
    _RE_GUILT_ADMITTED: re.Pattern[str] = re.compile(
        r"(?:"
        r"признал(?:а|и|о)?\s+(?:свою\s+)?вин[уы]"
        r"|не\s+оспаривает"
        r"|согласил(?:ся|ась|ись)\s+с"
        r"|вину\s+признал"
        r"|свою\s+вину\s+признал"
        r"|не\s+отрицает\s+(?:своей\s+)?вин"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: протокол об отстранении
    # ------------------------------------------------------------------

    #: Протокол об отстранении от управления ТС
    _RE_REMOVAL_PROTOCOL: re.Pattern[str] = re.compile(
        r"(?:"
        r"протокол\w*\s+об\s+отстранени"
        r"|отстранени\w+\s+от\s+управлени"
        r"|отстранён\s+от\s+управлени"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: объяснения понятых / свидетелей
    # ------------------------------------------------------------------

    #: Объяснения/показания понятых
    _RE_WITNESS_EXPLANATIONS: re.Pattern[str] = re.compile(
        r"(?:"
        r"объяснени\w+\s+(?:понят\w+|свидетел\w+)"
        r"|показани\w+\s+(?:понят\w+|свидетел\w+)"
        r"|понят\w+\s+(?:подтвержда\w+|пояснил\w+|показал\w+|сообщил\w+)"
        r"|свидетел\w+\s+(?:подтвержда\w+|пояснил\w+|показал\w+)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: рапорт должностного лица ГИБДД
    # ------------------------------------------------------------------

    #: Рапорт/донесение сотрудника ГИБДД / ДПС
    _RE_POLICE_REPORT: re.Pattern[str] = re.compile(
        r"(?:"
        r"рапорт\w*\s+(?:сотрудник|инспектор|должностн)"
        r"|рапорт\w*\s+(?:ГИБДД|ДПС|ППС|ОВД)"
        r"|(?:сотрудник|инспектор)\w*\s+(?:ГИБДД|ДПС)\w*\s+(?:составил|доложил|рапортовал)"
        r"|рапорт\s+инспектор"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: свидетельство о поверке прибора
    # ------------------------------------------------------------------

    #: Свидетельство о поверке / сертификат на алкотестер
    _RE_DEVICE_CERTIFICATE: re.Pattern[str] = re.compile(
        r"(?:"
        r"свидетельств\w+\s+о\s+поверк"
        r"|сертификат\w*\s+(?:о\s+)?поверк"
        r"|(?:алкотестер|измерительн\w+\s+прибор)\w*\s+(?:прошёл|прошел|имеет)\s+поверк"
        r"|поверк\w+\s+(?:прибор|алкотестер|средств)"
        r"|(?:действующ\w+|действительн\w+)\s+(?:поверк|сертификат)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: исправность автомобиля
    # ------------------------------------------------------------------

    #: Транспортное средство исправно / техническое состояние
    _RE_VEHICLE_OPERATIONAL: re.Pattern[str] = re.compile(
        r"(?:"
        r"автомобил\w+\s+(?:исправен|исправно|в\s+исправном)"
        r"|технически\s+исправн"
        r"|транспортн\w+\s+средств\w+\s+исправн"
        r"|неисправност\w+\s+(?:не\s+)?(?:обнаружен|выявлен|установлен)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: особый порядок
    # ------------------------------------------------------------------

    #: Рассмотрение в особом/упрощённом порядке
    _RE_SPECIAL_PROCEDURE: re.Pattern[str] = re.compile(
        r"(?:"
        r"особ\w+\s+порядк"
        r"|упрощённ\w+\s+порядк"
        r"|упрощенн\w+\s+порядк"
        r"|в\s+особом\s+порядке"
        r"|особый\s+порядок"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: ранение водителя
    # ------------------------------------------------------------------

    #: Водитель получил травму / ранение
    _RE_DRIVER_INJURED: re.Pattern[str] = re.compile(
        r"(?:"
        r"водитель\w*\s+(?:получил|причинен\w*|нанесен\w*)\s+(?:травм|вред|поврежден|ранен)"
        r"|(?:водитель|он|она)\s+(?:был\s+)?ранен\w*"
        r"|(?:телесн\w+\s+поврежден\w+|травм\w+)\s+водител"
        r")",
        re.IGNORECASE,
    )

    #: Водитель тяжело ранен / в тяжёлом состоянии
    _RE_DRIVER_CRITICAL: re.Pattern[str] = re.compile(
        r"(?:"
        r"водитель\w*\s+(?:получил|причинен\w*)\s+тяжк\w+"
        r"|тяжк\w+\s+(?:вред|поврежден|ранен)\w*\s+водител"
        r"|водитель\w*\s+в\s+тяжёлом\s+состояни"
        r"|водитель\w*\s+в\s+тяжелом\s+состояни"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: ранение жертвы
    # ------------------------------------------------------------------

    #: Жертва (пассажир/пешеход) ранена
    _RE_VICTIM_INJURED: re.Pattern[str] = re.compile(
        r"(?:"
        r"(?:пассажир|пешеход|потерпевш)\w*\s+(?:получил|причинен|нанесен)\w*\s+(?:травм|вред|поврежден|ранен)"
        r"|(?:пассажир|пешеход|потерпевш)\w*\s+(?:был\s+)?ранен\w*"
        r"|(?:телесн\w+\s+поврежден\w+|травм\w+)\s+(?:пассажир|пешеход|потерпевш)"
        r"|вред\s+здоровью\s+(?:пассажир|пешеход|потерпевш|граждан)"
        r")",
        re.IGNORECASE,
    )

    #: Жертва погибла
    _RE_VICTIM_DEAD: re.Pattern[str] = re.compile(
        r"(?:"
        r"(?:смерт|гибел|погиб)\w+\s+(?:пассажир|пешеход|потерпевш|граждан)"
        r"|(?:пассажир|пешеход|потерпевш|граждан)\w+\s+(?:погиб|скончал|умер)"
        r"|наступил(?:а|о)?\s+смерть"
        r")",
        re.IGNORECASE,
    )

    #: Жертва тяжело ранена
    _RE_VICTIM_CRITICAL: re.Pattern[str] = re.compile(
        r"(?:"
        r"тяжк\w+\s+вред\s+здоровью\s+(?:пассажир|пешеход|потерпевш)"
        r"|(?:пассажир|пешеход|потерпевш)\w*\s+(?:получил|причинен)\w*\s+тяжк"
        r"|в\s+тяжёлом\s+состояни\w+\s+(?:пассажир|пешеход|потерпевш)"
        r"|в\s+тяжелом\s+состояни\w+\s+(?:пассажир|пешеход|потерпевш)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: рецидив
    # ------------------------------------------------------------------

    #: Ранее привлекался / повторное нарушение
    _RE_RECIDIVISM: re.Pattern[str] = re.compile(
        r"(?:"
        r"ранее\s+(?:уже\s+)?(?:привлекал|был\s+привлечён|был\s+привлечен)"
        r"|повторн\w+\s+(?:лишени|нарушени|совершени)"
        r"|(?:неоднократно|вновь)\s+(?:лишал|привлекал|нарушал)"
        r"|подвергалс\w+\s+(?:административн|наказани)"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: штраф (из предыдущих дел)
    # ------------------------------------------------------------------

    #: Штраф ранее выплачен
    _RE_PREV_FINE_PAID: re.Pattern[str] = re.compile(
        r"штраф\w*\s+(?:был\s+)?(?:уплачен|выплачен|оплачен|погашен)",
        re.IGNORECASE,
    )

    #: Штраф ранее не выплачен
    _RE_PREV_FINE_UNPAID: re.Pattern[str] = re.compile(
        r"штраф\w*\s+(?:не\s+(?:был\s+)?(?:уплачен|выплачен|оплачен)|задолженност)",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Константы: водительское удостоверение из предыдущих дел
    # ------------------------------------------------------------------

    #: Права ранее сданы
    _RE_PREV_LICENSE_SURRENDERED: re.Pattern[str] = re.compile(
        r"(?:"
        r"(?:водительское\s+удостоверение|права)\s+(?:был[ои]\s+)?(?:сдан|изъят|сданы|изъяты)"
        r"|сдал\w*\s+(?:водительское\s+)?удостоверени"
        r")",
        re.IGNORECASE,
    )

    #: Права ранее не сданы
    _RE_PREV_LICENSE_NOT_SURRENDERED: re.Pattern[str] = re.compile(
        r"(?:"
        r"(?:водительское\s+удостоверение|права)\s+не\s+(?:был[ои]\s+)?(?:сдан|изъят)"
        r"|не\s+сдал\w*\s+(?:водительское\s+)?удостоверени"
        r")",
        re.IGNORECASE,
    )

    # ------------------------------------------------------------------
    # Публичный API
    # ------------------------------------------------------------------

    def extract_medical_examination(self, text: str) -> int:
        """Определяет факт медицинского освидетельствования.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            1 — освидетельствование не проводилось;
            2 — освидетельствование проведено;
            3 — водитель отказался от освидетельствования.
        """
        if not text:
            return 1
        if self._RE_MED_REFUSED.search(text):
            return 3
        if self._RE_MED_CONDUCTED.search(text):
            return 2
        return 1

    def extract_alcohol_level_known(self, text: str) -> bool:
        """Определяет, известно ли числовое значение концентрации алкоголя.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если в тексте найдено числовое значение промилле / мг/л.
        """
        if not text:
            return False
        return bool(self._RE_ALCOHOL_LEVEL.search(text))

    def extract_guilt_admitted(self, text: str) -> bool:
        """Определяет, признал ли водитель вину.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если найдено признание вины или фраза о непротивоборстве.
        """
        if not text:
            return False
        return bool(self._RE_GUILT_ADMITTED.search(text))

    def extract_has_removal_protocol(self, text: str) -> bool:
        """Проверяет наличие протокола об отстранении от управления ТС.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если в тексте упоминается протокол об отстранении.
        """
        if not text:
            return False
        return bool(self._RE_REMOVAL_PROTOCOL.search(text))

    def extract_has_witness_explanations(self, text: str, witnesses_count: float | int | None = None) -> bool:
        """Проверяет наличие объяснений понятых/свидетелей.

        Признак True, если в тексте есть упоминание объяснений понятых/свидетелей
        ИЛИ witnesses_count > 0.

        Args:
            text: Текст обстоятельств дела.
            witnesses_count: Количество свидетелей из колонки witnesses_count.

        Returns:
            True, если есть показания свидетелей или их количество > 0.
        """
        if witnesses_count is not None:
            try:
                if float(witnesses_count) > 0:
                    return True
            except (ValueError, TypeError):
                pass
        if not text:
            return False
        return bool(self._RE_WITNESS_EXPLANATIONS.search(text))

    def extract_has_police_report(self, text: str) -> bool:
        """Проверяет наличие рапорта должностного лица ГИБДД.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если найден рапорт сотрудника ГИБДД/ДПС.
        """
        if not text:
            return False
        return bool(self._RE_POLICE_REPORT.search(text))

    def extract_has_device_certificate(self, text: str) -> bool:
        """Проверяет наличие свидетельства о поверке технического средства.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если найдено упоминание свидетельства/сертификата поверки прибора.
        """
        if not text:
            return False
        return bool(self._RE_DEVICE_CERTIFICATE.search(text))

    def extract_vehicle_operational(self, text: str) -> bool:
        """Проверяет, упоминается ли исправность транспортного средства.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если в тексте есть упоминание исправного автомобиля.
        """
        if not text:
            return False
        return bool(self._RE_VEHICLE_OPERATIONAL.search(text))

    def extract_special_procedure(self, text: str) -> bool:
        """Проверяет, рассматривалось ли дело в особом/упрощённом порядке.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если упоминается особый или упрощённый порядок рассмотрения.
        """
        if not text:
            return False
        return bool(self._RE_SPECIAL_PROCEDURE.search(text))

    def extract_driver_injured(self, text: str) -> bool:
        """Проверяет, получил ли водитель травму.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если упоминается ранение или травма водителя.
        """
        if not text:
            return False
        return bool(self._RE_DRIVER_INJURED.search(text))

    def extract_driver_health_status(self, text: str) -> int:
        """Возвращает статус здоровья водителя.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            0 — здоров / не упоминается;
            1 — ранен;
            2 — тяжело ранен.
        """
        if not text:
            return 0
        if self._RE_DRIVER_CRITICAL.search(text):
            return 2
        if self._RE_DRIVER_INJURED.search(text):
            return 1
        return 0

    def extract_victim_injured(self, text: str) -> bool:
        """Проверяет, пострадал ли потерпевший (пассажир/пешеход).

        Args:
            text: Текст обстоятельств дела.

        Returns:
            True, если упоминается ранение или гибель жертвы.
        """
        if not text:
            return False
        return bool(
            self._RE_VICTIM_INJURED.search(text)
            or self._RE_VICTIM_DEAD.search(text)
            or self._RE_VICTIM_CRITICAL.search(text)
        )

    def extract_victim_health_status(self, text: str) -> int:
        """Возвращает статус здоровья жертвы.

        Args:
            text: Текст обстоятельств дела.

        Returns:
            0 — нет жертвы или жертва здорова;
            1 — ранена (лёгкий/средний вред);
            2 — тяжело ранена;
            3 — погибла.
        """
        if not text:
            return 0
        if self._RE_VICTIM_DEAD.search(text):
            return 3
        if self._RE_VICTIM_CRITICAL.search(text):
            return 2
        if self._RE_VICTIM_INJURED.search(text):
            return 1
        return 0

    def extract_previous_fine_status(self, text: str, is_repeat_offense: bool = False) -> int:
        """Определяет статус ранее назначенного штрафа.

        Args:
            text: Текст обстоятельств дела.
            is_repeat_offense: Флаг повторного нарушения из датасета.

        Returns:
            1 — штраф ранее не назначался;
            2 — штраф назначался, но не выплачен;
            3 — штраф назначался и выплачен.
        """
        if not text and not is_repeat_offense:
            return 1
        if self._RE_PREV_FINE_PAID.search(text or ""):
            return 3
        if self._RE_PREV_FINE_UNPAID.search(text or ""):
            return 2
        # Повторное нарушение без явного упоминания штрафа — неизвестно, возвращаем 2
        if is_repeat_offense:
            return 2
        return 1

    def extract_previous_license_status(self, text: str, is_repeat_offense: bool = False) -> int:
        """Определяет статус ранее назначенного лишения прав.

        Args:
            text: Текст обстоятельств дела.
            is_repeat_offense: Флаг повторного нарушения из датасета.

        Returns:
            1 — лишение прав ранее не назначалось;
            2 — назначалось, но права не сданы;
            3 — назначалось и права сданы.
        """
        if not text and not is_repeat_offense:
            return 1
        if self._RE_PREV_LICENSE_SURRENDERED.search(text or ""):
            return 3
        if self._RE_PREV_LICENSE_NOT_SURRENDERED.search(text or ""):
            return 2
        if is_repeat_offense:
            return 2
        return 1

    def extract_recidivism_count(self, text: str, is_repeat_offense: bool = False) -> int:
        """Подсчитывает количество упоминаний рецидивизма в тексте.

        Args:
            text: Текст обстоятельств дела.
            is_repeat_offense: Флаг повторного нарушения из датасета.

        Returns:
            Количество упоминаний рецидивизма (минимум 1, если is_repeat_offense=True).
        """
        count = 0
        if text:
            count = len(self._RE_RECIDIVISM.findall(text))
        if is_repeat_offense and count == 0:
            count = 1
        return count
